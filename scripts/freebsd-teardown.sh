#!/bin/sh
#
# freebsd-teardown.sh - undo what scripts/freebsd-setup.sh configured.
#
# Stops virtual_oss and restores the most recent asound.conf backup (if any). It does
# NOT unload cuse or remove packages, since those may be used by other software.
#
# Run as root:
#     sh scripts/freebsd-teardown.sh

set -eu

ASOUND_CONF="${ASOUND_CONF:-/usr/local/etc/asound.conf}"

log() { printf '[teardown] %s\n' "$*"; }
die() { printf '[teardown] ERROR: %s\n' "$*" >&2; exit 1; }

[ "$(id -u)" -eq 0 ] || die "must run as root (try: sudo sh $0)"

if pgrep -q virtual_oss 2>/dev/null; then
	log "stopping virtual_oss"
	pkill virtual_oss || true
else
	log "no virtual_oss running"
fi

# Restore the newest backup this tool created, if present.
newest_backup="$(ls -1t "${ASOUND_CONF}".bak.* 2>/dev/null | head -n 1 || true)"
if [ -n "${newest_backup:-}" ]; then
	log "restoring $newest_backup -> $ASOUND_CONF"
	mv "$newest_backup" "$ASOUND_CONF"
elif [ -f "$ASOUND_CONF" ] && grep -q "lan-audio-bridge" "$ASOUND_CONF" 2>/dev/null; then
	log "removing generated $ASOUND_CONF (no backup to restore)"
	rm -f "$ASOUND_CONF"
else
	log "leaving $ASOUND_CONF untouched (not generated by this tool)"
fi

# Restore a ~/.asoundrc that setup moved aside, if any.
user_rc="${HOME:-/root}/.asoundrc"
newest_rc_backup="$(ls -1t "${user_rc}".bak.* 2>/dev/null | head -n 1 || true)"
if [ -n "${newest_rc_backup:-}" ]; then
	log "restoring $newest_rc_backup -> $user_rc"
	mv "$newest_rc_backup" "$user_rc"
fi

log "done. cuse and packages were left in place."
